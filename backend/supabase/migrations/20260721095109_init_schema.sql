-- ============================================================================
-- Around You — initial schema
-- ============================================================================
-- Mirrors app/appdb/schema.go exactly (Accommodation, Restaurant, ServiceData,
-- AttractionData, User, ProfileSettings, sessions), which was itself built by
-- reading every frontend Form/List/Tab component's actual field usage — see
-- the Phase 1 architecture report. Applying this + rewiring app/appdb's Store
-- to issue real queries (via encore.dev/storage/sqldb) replaces the in-memory
-- map store with this database.
--
-- HOW TO APPLY
--   Supabase CLI:  supabase db push
--   Or paste this whole file into the Supabase Dashboard's SQL Editor and run it.
--
-- CONNECTION MODEL / RLS NOTE (read before enabling this in production)
--   This app has its own auth (email/access-code -> session token in the
--   `sessions` table below), not Supabase Auth. The Encore backend should
--   connect with a role that bypasses RLS entirely — Supabase's `service_role`
--   key if you're going through Supabase's pooler/PostgREST, or a plain
--   Postgres role with BYPASSRLS if Encore connects directly (the more likely
--   setup, since Encore talks straight to Postgres, not through PostgREST).
--   The RLS policies below are a *defense-in-depth* baseline for the
--   `anon`/`authenticated` roles only, in case the frontend or something else
--   ever queries Supabase directly with the anon key. They intentionally
--   expose nothing except read-only access to already-public, active listings.
-- ============================================================================


-- ============================================================================
-- Extensions
-- ============================================================================
create extension if not exists pgcrypto; -- gen_random_uuid(), not required yet but cheap to have on hand


-- ============================================================================
-- Shared trigger: keep updated_at current on every UPDATE
-- ============================================================================
create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


