-- needed for accommodations too, switch to PostGIS geography + a GiST index
-- (see the note above ListNearby on restaurants/services/attractions below).
create index idx_accommodations_lat_lng on accommodations (latitude, longitude);

create trigger trg_accommodations_updated_at
  before update on accommodations
  for each row execute function set_updated_at();


