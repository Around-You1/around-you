-- ============================================================================
-- users
-- Matches appdb.User. NOTE: auth.go's AccessCodeLogin/SecondaryLogin currently
-- create a brand-new user row on every login rather than reusing one (only
-- LocalGuestLogin dedupes, by role+email) — this schema intentionally does
-- NOT add a unique constraint on email, or rows would start failing to insert
-- the moment two guests share a synthetic "guest@<business name>" email.
-- Tighten this once/if the login handlers are changed to dedupe guests too.
-- ============================================================================
create table users (
  id                 bigint generated by default as identity primary key,

  email              text not null,
  role               text not null
                       check (role in ('Guest', 'LocalGuest', 'Partner', 'SuperAdmin')),
  profile_type       text
                       check (profile_type is null or profile_type in ('accommodation', 'restaurant', 'service', 'attraction')),

  accommodation_id   bigint references accommodations (id) on delete set null,

  -- entity_type/entity_id together are a polymorphic reference into
  -- restaurants/services/attractions depending on entity_type. Postgres has
  -- no native polymorphic FK — enforce with a trigger below rather than a
  -- plain FK constraint (or normalize into per-type nullable FK columns if
  -- you'd rather trade the trigger for three always-nullable FKs).
  entity_type        text
                       check (entity_type is null or entity_type in ('restaurant', 'service', 'attraction')),
  entity_id          bigint,

  area               text,
  municipality       text,

  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create index idx_users_accommodation_id on users (accommodation_id);
create index idx_users_entity on users (entity_type, entity_id);
create index idx_users_role_email on users (role, email);

create trigger trg_users_updated_at
  before update on users
  for each row execute function set_updated_at();

-- Polymorphic FK enforcement: whenever entity_type/entity_id is set, make
-- sure it actually points at an existing row in the right table.
create or replace function check_user_entity_reference()
returns trigger
language plpgsql
as $$
begin
  if new.entity_type is null then
    return new;
  end if;

  if new.entity_type = 'restaurant' and not exists (select 1 from restaurants where id = new.entity_id) then
    raise exception 'users.entity_id % does not reference an existing restaurant', new.entity_id;
  elsif new.entity_type = 'service' and not exists (select 1 from services where id = new.entity_id) then
    raise exception 'users.entity_id % does not reference an existing service', new.entity_id;
  elsif new.entity_type = 'attraction' and not exists (select 1 from attractions where id = new.entity_id) then
    raise exception 'users.entity_id % does not reference an existing attraction', new.entity_id;
  end if;

  return new;
end;
$$;

create trigger trg_users_check_entity_reference
  before insert or update on users
  for each row execute function check_user_entity_reference();


-- ============================================================================
-- sessions
-- Matches appdb.Store.Sessions (token -> user ID). Bearer tokens minted by
-- auth.go's issueSession.
-- ============================================================================
create table sessions (
  token       text primary key,
  user_id     bigint not null references users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  -- Not read by the current Go handlers (auth.go never checks expiry), but
  -- worth having in the schema so expiry can be added without a migration —
  -- e.g. `delete from sessions where expires_at < now()` on a cron.
  expires_at  timestamptz
);

create index idx_sessions_user_id on sessions (user_id);


