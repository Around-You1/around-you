-- ============================================================================
-- Row Level Security
-- See the connection-model note at the top of this file before relying on
-- these. Locked down by default; only read access to already-public, active
-- listings is opened up for anon/authenticated.
-- ============================================================================
alter table accommodations   enable row level security;
alter table restaurants      enable row level security;
alter table services         enable row level security;
alter table attractions      enable row level security;
alter table users            enable row level security;
alter table sessions         enable row level security;
alter table profile_settings enable row level security;

-- Public, read-only access to active listings only (mirrors what guests can
-- already see through the app itself via GuestDashboard.tsx's
-- listByMunicipality/listNearby). Everything else — inserts, updates,
-- deletes, and all of users/sessions/profile_settings — has no anon/
-- authenticated policy at all, so it's denied by default under RLS.
create policy "Public can read active accommodations"
  on accommodations for select
  to anon, authenticated
  using (is_active = true);

create policy "Public can read active restaurants"
  on restaurants for select
  to anon, authenticated
  using (is_active = true);

create policy "Public can read active services"
  on services for select
  to anon, authenticated
  using (is_active = true);

create policy "Public can read active attractions"
  on attractions for select
  to anon, authenticated
  using (is_active = true);

-- profile_settings (logo, booking/social links) is app-wide marketing info,
-- safe to expose publicly for read — matches LogoPlaceholder.tsx and
-- BookingsSocialsDropdowns.tsx both being reachable from public/guest screens.
create policy "Public can read platform profile settings"
  on profile_settings for select
  to anon, authenticated
  using (true);


