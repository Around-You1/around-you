-- ============================================================================
-- 000003_null_safety_defaults
-- ============================================================================
-- The COALESCE fixes in store/sql_store.go and app/auth/auth.go stop NULLs
-- from crashing a scan today, but they only help if every future SELECT
-- remembers to include them. This migration removes the underlying
-- possibility instead: backfill every existing NULL to '' (or 0 for the
-- nullable bigints), then set a DEFAULT so newly inserted rows can't
-- reintroduce a NULL in these columns even via a manual INSERT that bypasses
-- the Go layer entirely (e.g. a one-off `psql` fix, a future migration, an
-- admin script).
--
-- Deliberately NOT adding NOT NULL constraints on top of the defaults: a
-- constraint would reject any existing external tooling that still inserts
-- explicit NULLs, whereas a DEFAULT only kicks in when the column is omitted
-- from the INSERT — strictly safer for a live system, at the cost of not
-- being a hard guarantee. If you want the hard guarantee later, add NOT NULL
-- in a follow-up migration once you've confirmed nothing still inserts NULL
-- explicitly.
-- ============================================================================

