-- (profile_reference_code and official_* deliberately left without a DEFAULT:
--  profile_reference_code is always explicitly generated by Create/Import in
--  Go, so a DB-level default would never actually be used; official_* fields
--  are legitimately "unset until an admin fills them in" and a blank default
--  isn't meaningfully different from NULL there beyond the scan safety this
--  migration's UPDATE above already provides.)

-- ---- users --------------------------------------------------------------
-- Same reasoning: profile_type/entity_type/area/municipality are nullable
-- and COALESCE'd in Go (auth.go), but backfilling removes the NULL outright
-- so a manual insert can't reintroduce it either.
update users set
  profile_type = coalesce(profile_type, ''),
  entity_type = coalesce(entity_type, ''),
  area = coalesce(area, ''),
  municipality = coalesce(municipality, '');

alter table users
  alter column profile_type set default '',
  alter column entity_type set default '',
  alter column area set default '',
  alter column municipality set default '';
-- accommodation_id / entity_id stay nullable bigints with no default —
-- these are genuinely "does this user have one or not" and Go already
-- COALESCEs them to 0 on read, which is the correct "not set" sentinel for
-- an int64 field with no natural zero-collision (id 0 is never issued by
-- `generated by default as identity`, which starts at 1).
